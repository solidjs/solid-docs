function ensureSourceCheckout(dir, ref) {
	if (!fs.existsSync(dir)) {
		git(["clone", "--filter=blob:none", "--sparse", REPO_URL, dir]);
	} else if (!fs.existsSync(path.join(dir, ".git"))) {
		throw new Error(`${dir} exists but is not a git checkout`);
	}

	git(["-C", dir, "sparse-checkout", "set", ...SPARSE_PATHS]);
	git(["-C", dir, "fetch", "origin", ref, "--depth=1"]);
	git(["-C", dir, "checkout", "--detach", "FETCH_HEAD"]);
}

function git(args) {
	return execFileSync("git", args, {
		encoding: "utf8",
		stdio: ["ignore", "pipe", "inherit"],
	});
}

function createProgram(root) {
	const options = {
		allowJs: false,
		allowSyntheticDefaultImports: true,
		esModuleInterop: true,
		jsx: ts.JsxEmit.Preserve,
		module: ts.ModuleKind.NodeNext,
		moduleResolution: ts.ModuleResolutionKind.NodeNext,
		noEmit: true,
		skipLibCheck: true,
		target: ts.ScriptTarget.ES2022,
		baseUrl: root,
		paths: {
			"solid-js": ["packages/solid/src/index.ts"],
			"@solidjs/signals": ["packages/signals/src/index.ts"],
			"@solidjs/web": ["packages/web/src/index.ts"],
			"@solidjs/web/server-functions": [
				"packages/web/server-functions/src/client.ts",
			],
			"@solidjs/web/server-functions/rich-args": [
				"packages/web/server-functions/src/rich-args.ts",
			],
			"@solidjs/web/storage": ["packages/web/storage/src/index.ts"],
		},
	};

	const rootNames = [
		...ENTRYPOINTS.map((entry) => path.join(root, entry.path)),
		...collectTsFiles(path.join(root, "packages/solid/src")),
		...collectTsFiles(path.join(root, "packages/web")),
		...collectTsFiles(path.join(root, "packages/signals/src")),
	];

	const host = ts.createCompilerHost(options);
	const originalResolve = ts.resolveModuleName;
	host.resolveModuleNames = (moduleNames, containingFile) =>
		moduleNames.map((moduleName) => {
			const alias = resolveAlias(root, moduleName);
			if (alias) {
				return {
					resolvedFileName: alias,
					extension: ts.Extension.Ts,
				};
			}

			if (moduleName.startsWith(".")) {
				const local = resolveLocalModule(containingFile, moduleName);
				if (local) {
					return {
						resolvedFileName: local,
						extension: ts.Extension.Ts,
					};
				}
			}

			return originalResolve(moduleName, containingFile, options, host)
				.resolvedModule;
		});

	return ts.createProgram([...new Set(rootNames)], options, host);
}

function resolveAlias(root, moduleName) {
	const aliases = {
		"solid-js": "packages/solid/src/index.ts",
		"@solidjs/signals": "packages/signals/src/index.ts",
		"@solidjs/web": "packages/web/src/index.ts",
		"@solidjs/web/server-functions":
			"packages/web/server-functions/src/client.ts",
		"@solidjs/web/server-functions/rich-args":
			"packages/web/server-functions/src/rich-args.ts",
		"@solidjs/web/storage": "packages/web/storage/src/index.ts",
	};
	return aliases[moduleName] ? path.join(root, aliases[moduleName]) : undefined;
}

function resolveLocalModule(containingFile, moduleName) {
	const base = path.resolve(path.dirname(containingFile), moduleName);
	const candidates = [
		base,
		base.replace(/\.js$/, ".ts"),
		`${base}.ts`,
		path.join(base, "index.ts"),
	];
	return candidates.find((candidate) => fs.existsSync(candidate));
}

function collectTsFiles(dir) {
	if (!fs.existsSync(dir)) return [];
	const files = [];
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const fullPath = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			files.push(...collectTsFiles(fullPath));
		} else if (
			entry.isFile() &&
			fullPath.endsWith(".ts") &&
			!fullPath.endsWith(".d.ts")
		) {
			files.push(fullPath);
		}
	}
	return files;
}

function collectEntries(program, checker, root) {
	const entries = [];
	const foldedEntries = [];
	const byName = new Map();
	const foldedByName = new Map();
	const missingNames = new Set();

	for (const entrypoint of ENTRYPOINTS) {
		const sourceFile = program.getSourceFile(path.join(root, entrypoint.path));
		if (!sourceFile) {
			throw new Error(`Entrypoint not found: ${entrypoint.path}`);
		}

		const moduleSymbol = checker.getSymbolAtLocation(sourceFile);
		if (!moduleSymbol) continue;

		for (const exportedSymbol of checker.getExportsOfModule(moduleSymbol)) {
			const name = exportedSymbol.getName();
			if (shouldSkipName(name)) continue;

			const symbol = resolveSymbol(checker, exportedSymbol);
			const declarations = declarationList(symbol).filter((declaration) =>
				isSourceDeclaration(root, declaration)
			);
			if (!declarations.length) continue;

			const docs = getDocs(declarations);
			const disposition = getDisposition(name, docs);
			if (disposition.type === "hidden") {
				continue;
			}
			if (disposition.type === "missing") {
				missingNames.add(name);
				continue;
			}
			const primary = selectPrimaryDeclaration(declarations);
			const entry = createEntry({
				name,
				entrypoint,
				primary,
				root,
				declarations,
				docs,
				checker,
				exportedSymbol,
				symbol,
				disposition,
			});

			if (disposition.type === "fold") {
				const existing = foldedByName.get(name);
				if (existing) {
					mergeDuplicateEntry(existing, entry);
				} else {
					foldedByName.set(name, entry);
					foldedEntries.push(entry);
				}
				continue;
			}

			const existing = byName.get(name);
			if (existing) {
				mergeDuplicateEntry(existing, entry);
			} else {
				byName.set(name, entry);
				entries.push(entry);
			}
		}
	}

	if (missingNames.size) {
		throw new Error(
			`Missing reference dispositions for exported symbols:\n${[...missingNames]
				.sort()
				.map((name) => `- ${name}`)
				.join(
					"\n"
				)}\nAdd each symbol to CANONICAL_ROUTES, ADVANCED_ROUTES, STANDALONE_TYPE_ROUTES, FOLD_INTO, HIDDEN_EXPORTS, or mark it @internal upstream.`
		);
	}

	augmentWithHydrationFields(foldedByName, program, root);

	return {
		pages: entries.sort(
			(a, b) =>
				a.route.outputPath.localeCompare(b.route.outputPath) ||
				a.name.localeCompare(b.name)
		),
		folds: foldedEntries.sort((a, b) => a.name.localeCompare(b.name)),
	};
}

function augmentWithHydrationFields(foldedByName, program, root) {
	const sourceFile = program.getSourceFile(
		path.join(root, "packages/solid/src/client/hydration.ts")
	);
	if (!sourceFile) return;
	const alias = sourceFile.statements.find(
		(statement) =>
			ts.isTypeAliasDeclaration(statement) &&
			statement.name.getText() === "HydrationSsrFields"
	);
	if (!alias) return;
	const members = getMemberDocs([alias]);
	if (!members.length) return;
	const memberLines = getTypeMembers([alias]).map(
		(member) => `  ${member.getText(sourceFile).replace(/\s+/g, " ").trim()}`
	);
	for (const name of HYDRATION_AUGMENTED_TYPES) {
		const entry = foldedByName.get(name);
		if (!entry) continue;
		const known = new Set(entry.memberDocs.map((member) => member.name));
		entry.memberDocs = [
			...entry.memberDocs,
			...members.filter((member) => !known.has(member.name)),
		];
		entry.signature = entry.signature.replace(
			/\n?\}\s*;?$/,
			`\n${memberLines.join("\n")}\n};`
		);
	}
}

function createEntry({
	name,
	entrypoint,
	primary,
	root,
	declarations,
	docs,
	checker,
	exportedSymbol,
	symbol,
	disposition,
}) {
	const sourceFilePath = primary.getSourceFile().fileName;
	const sourcePath = relativePath(root, sourceFilePath);
	const line =
		primary.getSourceFile().getLineAndCharacterOfPosition(primary.getStart())
			.line + 1;
	const summaryOverride = ENTRY_SUMMARY_OVERRIDES[name];
	currentEntryName = name;
	return {
		name,
		packageName: entrypoint.packageName,
		kind: getKind(primary),
		sourcePath,
		line,
		docs: summaryOverride
			? {
					...docs,
					summary: summaryOverride,
					description: "",
					remarks: "",
				}
			: docs,
		signature:
			SIGNATURE_OVERRIDES[name] ?? getSignature(name, declarations, checker),
		memberDocs: OMIT_MEMBER_DOCS.has(name) ? [] : getMemberDocs(declarations),
		...getCallableDocs(name, declarations, docs, checker),
		route: disposition.route,
		foldTargets: disposition.targets ?? [],
		aliases: getExportAliases(name, exportedSymbol, symbol),
	};
}

function mergeDuplicateEntry(existing, incoming) {
	if (incoming.sourcePath === PREFERRED_SOURCE_PATHS[incoming.name]) {
		existing.sourcePath = incoming.sourcePath;
		existing.line = incoming.line;
	}
	if (
		incoming.packageName.startsWith("@solidjs/web/server-functions") &&
		!existing.packageName.startsWith("@solidjs/web/server-functions")
	) {
		existing.packageName = incoming.packageName;
	}
	if (!existing.docs.summary && incoming.docs.summary) {
		existing.kind = incoming.kind;
		existing.sourcePath = incoming.sourcePath;
		existing.line = incoming.line;
		existing.docs = incoming.docs;
		existing.signature = incoming.signature;
		existing.aliases = incoming.aliases;
		existing.parameters = incoming.parameters;
		existing.props = incoming.props;
		existing.isComponent = incoming.isComponent;
		return;
	}
	// Both sides documented (for example the solid-js hydration wrapper and
	// the @solidjs/signals core): keep the first summary but borrow any
	// examples, returns, and parameter text the wrapper does not carry.
	if (!existing.docs.examples.length && incoming.docs.examples.length) {
		existing.docs = { ...existing.docs, examples: incoming.docs.examples };
	}
	if (!existing.docs.returns && incoming.docs.returns) {
		existing.docs = { ...existing.docs, returns: incoming.docs.returns };
	}
	if (!existing.docs.params.length && incoming.docs.params.length) {
		existing.docs = { ...existing.docs, params: incoming.docs.params };
	}
	existing.parameters = borrowMemberText(
		existing.parameters,
		incoming.parameters
	);
	existing.props = borrowMemberText(existing.props, incoming.props);
}

// Keeps the existing member list (names and types) but fills in missing
// descriptions from a duplicate declaration, matched by member name.
function borrowMemberText(existing, incoming) {
	if (!existing.length) return incoming;
	const textByName = new Map(
		incoming.filter((member) => member.text).map((m) => [m.name, m.text])
	);
	return existing.map((member) =>
		member.text || !textByName.has(member.name)
			? member
			: { ...member, text: textByName.get(member.name) }
	);
}

function shouldSkipName(name) {
	return false;
}

function resolveSymbol(checker, symbol) {
	if ((symbol.flags & ts.SymbolFlags.Alias) !== 0) {
		try {
			return checker.getAliasedSymbol(symbol);
		} catch {
			return symbol;
		}
	}
	return symbol;
}

function declarationList(symbol) {
	return symbol.declarations ?? [];
}

function isSourceDeclaration(root, declaration) {
	const fileName = declaration.getSourceFile().fileName;
	return fileName.startsWith(path.join(root, "packages"));
}

function selectPrimaryDeclaration(declarations) {
	const withDocs = declarations.find(
		(declaration) => getDocs([declaration]).summary
	);
	return withDocs ?? declarations[0];
}

function getKind(declaration) {
	if (
		ts.isInterfaceDeclaration(declaration) ||
		ts.isTypeAliasDeclaration(declaration) ||
		ts.isTypeParameterDeclaration(declaration)
	) {
		return "type";
	}
	if (ts.isModuleDeclaration(declaration)) {
		return "namespace";
	}
	return "value";
}

function getDocs(declarations) {
	const result = {
		summary: "",
		params: [],
		returns: "",
		examples: [],
		see: [],
		related: [],
		useCases: "",
		tags: [],
		deprecated: "",
		internal: false,
		remarks: "",
		description: "",
	};

	for (const declaration of declarations) {
		const docs = jsDocsOf(declaration);
		for (const doc of docs) {
			const summary = normalizeMarkdown(renderComment(doc.comment));
			if (summary) result.summary = summary;

			for (const tag of doc.tags ?? []) {
				const tagName = tag.tagName.getText();
				const normalizedTagName = normalizeTagName(tagName);
				const comment = normalizeMarkdown(renderComment(tag.comment));
				if (tagName === "param" && ts.isJSDocParameterTag(tag)) {
					result.params.push({
						name: tag.name.getText(),
						text: comment,
					});
				} else if (tagName === "returns" || tagName === "return") {
					result.returns = comment;
				} else if (tagName === "example") {
					if (comment) result.examples.push(comment);
				} else if (tagName === "see") {
					const see = normalizeMarkdown(renderSeeTag(tag));
					if (see) result.see.push(see);
				} else if (tagName === "deprecated") {
					result.deprecated = comment || "Deprecated.";
				} else if (tagName === "internal") {
					result.internal = true;
				} else if (tagName === "remarks") {
					result.remarks = comment;
				} else if (tagName === "description") {
					result.description = comment;
				} else if (normalizedTagName === "solidusecases") {
					const values = parseCsvTag(comment);
					if (values.length) result.useCases = values.join(", ");
				} else if (normalizedTagName === "solidtags") {
					result.tags.push(...parseCsvTag(comment));
				} else if (normalizedTagName === "solidrelated") {
					result.related.push(...parseCsvTag(comment));
				}
			}
		}
	}

	result.see = uniqueStrings(result.see);
	result.related = uniqueStrings(result.related);
	result.tags = uniqueStrings(result.tags);

	return result;
}

// JSDoc for `export const x = ...` hangs off the VariableStatement, not the
// VariableDeclaration that the symbol points at.
function jsDocsOf(declaration) {
	if (declaration.jsDoc?.length) return declaration.jsDoc;
	if (ts.isVariableDeclaration(declaration)) {
		const statement = declaration.parent?.parent;
		if (statement && ts.isVariableStatement(statement)) {
			return statement.jsDoc ?? [];
		}
	}
	return [];
}

function renderComment(comment) {
	if (!comment) return "";
	if (typeof comment === "string") return comment;
	return comment.map((part) => renderCommentPart(part)).join("");
}

function renderCommentPart(part) {
	if (
		ts.isJSDocLink?.(part) ||
		ts.isJSDocLinkCode?.(part) ||
		ts.isJSDocLinkPlain?.(part)
	) {
		return renderDocLink(part);
	}
	if (typeof part.text === "string") return part.text;
	return part.getText?.() ?? "";
}

function renderDocLink(part) {
	const name = part.name?.getText?.();
	const text = part.text?.trim();
	const label = text || name;
	if (name) {
		const route = getRouteForSymbol(name);
		if (route) {
			const href = toReferenceHref(route.outputPath);
			return `[${escapeLinkLabel(label || name)}](${href})`;
		}
	}
	return label ? `\`${label}\`` : "";
}

function normalizeMarkdown(value) {
	const normalized = String(value)
		.replace(/\r\n/g, "\n")
		.replace(/^\s+\*\s/gm, "")
		.replace(/\[([A-Z][A-Z0-9_]{2,})\](?!\()/g, "`$1`")
		.trim();

	return capitalizeSentences(normalized);
}

function capitalizeSentences(value) {
	if (!value) return value;
	return splitFencedCode(value)
		.map((part) =>
			part.fence ? part.text : capitalizeSentencesInPlainText(part.text)
		)
		.join("");
}

function capitalizeSentencesInPlainText(value) {
	const inlineCode = [];
	const abbreviations = [];
	const masked = value
		.replace(/`[^`]*`/g, (code) => {
			const index = inlineCode.push(code) - 1;
			return `\uE000${index}\uE001`;
		})
		.replace(/\b(?:e\.g|i\.e)\./gi, (abbreviation) => {
			const index = abbreviations.push(abbreviation) - 1;
			return `\uE002${index}\uE003`;
		});
	return masked
		.replace(
			/(^|[.!?]\s+|\n{2,}\s*|\n\s*(?:[-*+]\s+|>\s+))([a-z])/g,
			(_match, prefix, first) => `${prefix}${first.toUpperCase()}`
		)
		.replace(/\uE000(\d+)\uE001/g, (_match, index) => inlineCode[Number(index)])
		.replace(
			/\uE002(\d+)\uE003/g,
			(_match, index) => abbreviations[Number(index)]
		);
}

function normalizeTagName(tagName) {
	return String(tagName)
		.toLowerCase()
		.replace(/[^a-z0-9]/g, "");
}

function parseCsvTag(value) {
	if (!value) return [];
	return value
		.split(/[\n,]/)
		.map((item) => item.trim())
		.filter(Boolean);
}

function uniqueStrings(values) {
	return [...new Set(values.map((value) => value.trim()).filter(Boolean))];
}

function renderSeeTag(tag) {
	const comment = renderComment(tag.comment);
	if (comment) return comment;
	const name = tag.name?.getText?.();
	if (name) return name;
	const raw = tag.getText?.() ?? "";
	return raw.replace(/^@see\s*/, "");
}

function getSignature(name, declarations, checker) {
	const functionDeclarations = declarations.filter(ts.isFunctionDeclaration);
	if (functionDeclarations.length) {
		const overloads = functionDeclarations.filter(
			(declaration) => !declaration.body
		);
		const targets = overloads.length ? overloads : functionDeclarations;
		return targets
			.map((declaration) =>
				cleanSignature(signatureFromNode(declaration, checker))
			)
			.join("\n");
	}

	const classDeclaration = declarations.find(ts.isClassDeclaration);
	if (classDeclaration)
		return cleanSignature(signatureFromNode(classDeclaration));

	const interfaceDeclaration = declarations.find(ts.isInterfaceDeclaration);
	if (interfaceDeclaration)
		return cleanSignature(
			stripMemberDocs(signatureFromNode(interfaceDeclaration))
		);

	const typeAlias = declarations.find(ts.isTypeAliasDeclaration);
	if (typeAlias)
		return cleanSignature(stripMemberDocs(signatureFromNode(typeAlias)));

	const variableDeclaration = declarations.find(ts.isVariableDeclaration);
	if (variableDeclaration) {
		const annotation = variableDeclaration.type;
		if (annotation && ts.isTypeQueryNode(annotation)) {
			// `const createEffect: typeof coreEffect` — follow the alias and
			// present the underlying overloads under the exported name.
			const target = checker.getSymbolAtLocation(annotation.exprName);
			const resolved = target ? resolveSymbol(checker, target) : undefined;
			const targetDeclarations = (
				resolved ? declarationList(resolved) : []
			).filter((declaration) => !ts.isVariableDeclaration(declaration));
			if (targetDeclarations.length) {
				return getSignature(name, targetDeclarations, checker).replace(
					/^function \w+/gm,
					`function ${name}`
				);
			}
		}
		if (annotation && !ts.isTypeQueryNode(annotation)) {
			const sourceFile = variableDeclaration.getSourceFile();
			// A const typed as a call-signature object or a function type is a
			// function to the reader; present it as overloads.
			if (
				ts.isTypeLiteralNode(annotation) &&
				annotation.members.length &&
				annotation.members.every(ts.isCallSignatureDeclaration)
			) {
				return annotation.members
					.map((member) =>
						cleanSignature(
							`function ${name}${dedent(member.getText(sourceFile))}`
						)
					)
					.join("\n");
			}
			if (ts.isFunctionTypeNode(annotation)) {
				const head = sourceFile.text
					.slice(
						annotation.getStart(sourceFile),
						annotation.type.getStart(sourceFile)
					)
					.replace(/=>\s*$/, "")
					.trim();
				return cleanSignature(
					`function ${name}${head}: ${annotation.type.getText(sourceFile)}`
				);
			}
			// Keep the author's formatting (and drop overload comments) when
			// the const carries an explicit type annotation.
			const text = annotation
				.getText(sourceFile)
				.replace(/^\s*\/\/.*$\n?/gm, "");
			return cleanSignature(`const ${name}: ${text}`);
		}
		const type = checker.typeToString(
			checker.getTypeOfSymbolAtLocation(
				checker.getSymbolAtLocation(variableDeclaration.name) ??
					checker.getTypeAtLocation(variableDeclaration).symbol,
				variableDeclaration
			),
			variableDeclaration,
			ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseFullyQualifiedType
		);
		return `const ${name}: ${type};`;
	}

	const enumDeclaration = declarations.find(ts.isEnumDeclaration);
	if (enumDeclaration)
		return cleanSignature(signatureFromNode(enumDeclaration));

	const primary = declarations[0];
	return cleanSignature(signatureFromNode(primary));
}

// Collects call-signature parameters (or component props) from the
// declarations so every function page can render `## Parameters` or
// `## Props` even when the upstream JSDoc has no `@param` tags.
function getCallableDocs(name, declarations, docs, checker) {
	const empty = { parameters: [], props: [], isComponent: false };
	const callDeclarations = collectCallDeclarations(declarations, checker);
	if (!callDeclarations.length) return empty;

	const first = callDeclarations[0];
	const isComponent =
		/^[A-Z]/.test(name) &&
		first.parameters.length === 1 &&
		first.parameters[0].name.getText() === "props";

	if (isComponent) {
		const override = PROP_DOCS[name];
		if (Array.isArray(override)) {
			return { parameters: [], props: override, isComponent: true };
		}
		return {
			parameters: [],
			props: mergeMembers(
				callDeclarations.map((declaration) =>
					propsFromDeclaration(declaration, checker)
				),
				override ?? {}
			),
			isComponent: true,
		};
	}

	// `@param` text first, then hand-written PARAM_DOCS on top (a string
	// replaces the text; an object can also pin the displayed type).
	const paramDocs = Object.fromEntries(
		docs.params.map((param) => [param.name, { text: param.text }])
	);
	for (const [paramName, doc] of Object.entries(PARAM_DOCS[name] ?? {})) {
		paramDocs[paramName] = {
			...(paramDocs[paramName] ?? {}),
			...(typeof doc === "string" ? { text: doc } : doc),
		};
	}
	const parameters = mergeMembers(
		callDeclarations.map((declaration) =>
			declaration.parameters.map((parameter) => ({
				// Some implementations underscore-prefix unused server-side
				// parameters; the reader sees the public name.
				name: parameter.name.getText().replace(/^_+/, ""),
				type: parameter.type
					? cleanTypeText(parameter.type.getText(parameter.getSourceFile()))
					: checker.typeToString(
							checker.getTypeAtLocation(parameter),
							parameter,
							ts.TypeFormatFlags.NoTruncation
						),
				optional: Boolean(parameter.questionToken || parameter.initializer),
				text: "",
			}))
		),
		paramDocs
	);
	return { parameters, props: [], isComponent: false };
}

function collectCallDeclarations(declarations, checker) {
	const functionDeclarations = declarations.filter(ts.isFunctionDeclaration);
	if (functionDeclarations.length) {
		const overloads = functionDeclarations.filter(
			(declaration) => !declaration.body
		);
		return overloads.length ? overloads : functionDeclarations;
	}
	const variableDeclaration = declarations.find(ts.isVariableDeclaration);
	if (!variableDeclaration) return [];
	const symbol = checker.getSymbolAtLocation(variableDeclaration.name);
	if (!symbol) return [];
	const type = checker.getTypeOfSymbolAtLocation(symbol, variableDeclaration);
	return type
		.getCallSignatures()
		.map((signature) => signature.getDeclaration())
		.filter(
			(declaration) =>
				declaration &&
				Array.isArray(declaration.parameters) &&
				declaration.parameters.length
		);
}

function propsFromDeclaration(declaration, checker) {
	const parameter = declaration.parameters[0];
	if (!parameter.type) return [];
	const type = checker.getTypeAtLocation(parameter.type);
	const properties = type.getProperties?.() ?? [];
	return properties.map((property) => {
		const declarationNode =
			property.valueDeclaration ?? property.declarations?.[0];
		const typeNode = declarationNode?.type;
		const typeText = typeNode
			? cleanTypeText(typeNode.getText(typeNode.getSourceFile()))
			: checker.typeToString(
					checker.getTypeOfSymbolAtLocation(property, parameter),
					parameter,
					ts.TypeFormatFlags.NoTruncation
				);
		return {
			name: property.getName(),
			type: typeText,
			optional: Boolean(property.flags & ts.SymbolFlags.Optional),
			text: normalizeMarkdown(
				ts.displayPartsToString(property.getDocumentationComment(checker))
			),
		};
	});
}

// Merges members across overloads by name, keeping first-seen order and
// collecting the distinct type texts. Descriptions come from `docsByName`
// (hand-written tables or `@param` tags) and fall back to source JSDoc.
function mergeMembers(memberLists, docsByName) {
	const merged = new Map();
	for (const members of memberLists) {
		for (const member of members) {
			const existing = merged.get(member.name);
			if (!existing) {
				merged.set(member.name, {
					name: member.name,
					types: [member.type],
					optional: member.optional,
					text: member.text,
				});
				continue;
			}
			if (!existing.types.includes(member.type))
				existing.types.push(member.type);
			existing.optional = existing.optional || member.optional;
			if (!existing.text && member.text) existing.text = member.text;
		}
	}
	return [...merged.values()].map((member) => {
		const doc = docsByName[member.name];
		const override = typeof doc === "object" && doc !== null ? doc : null;
		return {
			name: member.name,
			type: override?.type ?? member.types.join(" | "),
			optional: override?.optional ?? member.optional,
			text: (override ? override.text : doc) ?? member.text ?? "",
		};
	});
}

// Removes one level of indentation from a multi-line member text so it can
// sit at column zero in a code block.
function dedent(value) {
	const lines = String(value).split("\n");
	if (lines.length < 2) return value;
	const indents = lines
		.slice(1)
		.filter((line) => line.trim())
		.map((line) => line.match(/^\s*/)[0].length);
	const shared = Math.min(...indents);
	return [lines[0], ...lines.slice(1).map((line) => line.slice(shared))].join(
		"\n"
	);
}

function cleanTypeText(value) {
	return rewriteTypeText(String(value).replace(/\s+/g, " ").trim());
}

function rewriteTypeText(value) {
	if (KEEP_BRAND_TYPES.has(currentEntryName)) return value;
	return TYPE_TEXT_REWRITES.reduce(
		(result, [pattern, replacement]) => result.replace(pattern, replacement),
		value
	);
}

function stripMemberDocs(value) {
	return value.replace(/\/\*\*[\s\S]*?\*\/\s*/g, "");
}

function getTypeMembers(declarations) {
	for (const declaration of declarations) {
		if (ts.isInterfaceDeclaration(declaration)) return declaration.members;
		if (
			ts.isTypeAliasDeclaration(declaration) &&
			declaration.type &&
			ts.isTypeLiteralNode(declaration.type)
		) {
			return declaration.type.members;
		}
	}
	return null;
}

function getMemberDocs(declarations) {
	const members = getTypeMembers(declarations);
	if (!members) return [];
	return members
		.map((member) => {
			if (!member.name) return null;
			const name = member.name.getText();
			const type = member.type
				? member.type.getText(member.getSourceFile())
				: "";
			const text = (member.jsDoc ?? [])
				.map((doc) => normalizeMarkdown(renderComment(doc.comment)))
				.filter(Boolean)
				.join("\n\n");
			return { name, type, text };
		})
		.filter(Boolean);
}

function signatureFromNode(node, checker) {
	const sourceFile = node.getSourceFile();
	if (ts.isFunctionDeclaration(node) && node.body) {
		const head = sourceFile.text
			.slice(node.getStart(sourceFile), node.body.getStart(sourceFile))
			.trim();
		// Implementations without an annotated return type still have one;
		// ask the checker so the signature is complete.
		if (!node.type && checker) {
			const signature = checker.getSignatureFromDeclaration(node);
			if (signature) {
				const returnType = checker.typeToString(
					checker.getReturnTypeOfSignature(signature),
					node,
					ts.TypeFormatFlags.NoTruncation
				);
				return `${head}: ${returnType};`;
			}
		}
		return `${head};`;
	}
	const text = node.getText(sourceFile);
	const withoutDocs = text.replace(/^\/\*\*[\s\S]*?\*\/\s*/g, "");
	return withoutDocs;
}

function cleanSignature(value) {
	return rewriteTypeText(
		value
			.replace(/\r\n/g, "\n")
			.replace(/^export\s+/gm, "")
			.replace(/^declare\s+/gm, "")
			.replace(/\n{3,}/g, "\n\n")
			.trim()
			.replace(/;?$/, ";")
	);
}

function getExportAliases(name, exportedSymbol, resolvedSymbol) {
	return exportedSymbol === resolvedSymbol ||
		exportedSymbol.getName() === resolvedSymbol.getName()
		? []
		: [resolvedSymbol.getName()].filter((alias) => alias !== name);
}

function getDisposition(name, docs) {
	if (docs.internal || HIDDEN_EXPORTS.has(name) || name.startsWith("$")) {
		return { type: "hidden" };
	}

	if (FOLD_INTO[name]) {
		return { type: "fold", targets: normalizeTargets(FOLD_INTO[name]) };
	}

	const route = getRouteForSymbol(name);
	if (route) {
		return { type: route.visibility, route };
	}

	return { type: "missing" };
}

function normalizeTargets(target) {
	return Array.isArray(target) ? target : [target];
}

function getRouteForSymbol(name) {
	for (const [type, routes] of [
		["canonical", CANONICAL_ROUTES],
		["advanced", ADVANCED_ROUTES],
		["type", STANDALONE_TYPE_ROUTES],
	]) {
		const mapped = routes[name];
		if (!mapped) continue;
		return {
			path: mapped[0],
			outputPath: orderRoutePath(mapped[0]),
			category: mapped[1],
			mapped: true,
			visibility: type,
		};
	}
}

function orderRoutePath(routePath) {
	const parts = routePath.split("/");
	return parts
		.map((part, index) => {
			if (index === 0) return TOP_LEVEL_ROUTE_ORDER[part] ?? part;
			if (parts[0] === "advanced" && index === 1) {
				return ADVANCED_ROUTE_ORDER[part] ?? part;
			}
			return part;
		})
		.join("/");
}

function buildOutputFiles(reference, source) {
	const grouped = new Map();
	for (const entry of reference.pages) {
		const routePath = entry.route.outputPath;
		const current = grouped.get(routePath);
		if (!current) {
			grouped.set(routePath, [entry]);
		} else {
			current.push(entry);
		}
	}

	const foldsByRoute = collectFoldsByRoute(reference.folds);

	return [...grouped.entries()].map(([routePath, routeEntries]) => {
		orderPageEntries(routePath, routeEntries);
		const primary = routeEntries[0];
		return {
			routePath,
			fullPath: path.join(outDir, routePath),
			content: applyReferenceFixups(
				renderMdx(
					routeEntries,
					primary.route.category,
					source,
					foldsByRoute.get(routePath) ?? []
				)
			),
		};
	});
}

// On pages that hold several exports, the export whose name matches the file
// (or, failing that, the first non-predicate export) leads the page. Without
// this, `redirect.mdx` would open with `isHref`.
function orderPageEntries(routePath, entries) {
	if (entries.length < 2) return;
	const stem = path.basename(routePath, ".mdx").replace(/^\(\d+\)/, "");
	const rank = (entry) => {
		if (PAGE_LEAD[stem] === entry.name) return -1;
		if (slugify(entry.name) === stem) return 0;
		if (stem.includes(slugify(entry.name))) return 1;
		if (/^is[A-Z]/.test(entry.name)) return 3;
		return 2;
	};
	entries.sort((a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name));
}

function applyReferenceFixups(content) {
	return REFERENCE_FIXUPS.reduce(
		(result, [pattern, replacement]) => result.replace(pattern, replacement),
		content
	);
}

function collectFoldsByRoute(folds) {
	const byRoute = new Map();
	for (const entry of folds) {
		for (const target of entry.foldTargets) {
			const route = getRouteForSymbol(target);
			if (!route) {
				throw new Error(
					`Fold target "${target}" for "${entry.name}" does not have a reference route.`
				);
			}
			const current = byRoute.get(route.outputPath);
			if (!current) {
				byRoute.set(route.outputPath, [entry]);
			} else if (!current.some((existing) => existing.name === entry.name)) {
				current.push(entry);
			}
		}
	}
	for (const entries of byRoute.values()) {
		entries.sort((a, b) => a.name.localeCompare(b.name));
	}
	return byRoute;
}

function renderMdx(entries, category, source, foldedEntries = []) {
	const primary = entries[0];
	const description = toDescription(
		applyReferenceFixups(
			escapeMdxText(primary.docs.summary.split("\n\n")[0]) ||
				`${primary.name} API reference.`
		)
	);
	const useCases =
		primary.docs.useCases ||
		`${humanizeCategory(category).toLowerCase()} api, ${primary.name.toLowerCase()} usage`;
	const tags = buildFrontmatterTags(entries, category);
	const title =
		entries.length === 1
			? primary.name
			: entries.map((entry) => entry.name).join(" / ");
	const frontmatter = [
		"---",
		`title: ${yamlString(title)}`,
		`category: ${yamlString(category)}`,
		`use_cases: ${yamlString(useCases)}`,
		"tags:",
		...tags.map((tag) => `  - ${yamlString(tag)}`),
		'version: "2.0"',
		`description: ${yamlString(description)}`,
		`source_repo: "solidjs/solid"`,
		`source_ref: ${yamlString(source.sourceRef)}`,
		`source_path: ${yamlString(primary.sourcePath)}`,
		"---",
	].join("\n");

	const visibleFolds = foldedEntries.filter(
		(entry) => !HIDDEN_RELATED_TYPES.has(entry.name)
	);
	const relatedTypes = visibleFolds.length
		? `\n\n${renderRelatedTypes(visibleFolds)}`
		: "";
	const learn = renderLearnLinks(entries, category);
	const learnBlock = learn.length
		? `\n\n## Learn more\n\n${learn.join("\n")}`
		: "";

	const body =
		entries.length === 1
			? renderEntry(primary, { heading: "##" })
			: renderMultiEntryPage(entries);

	return `${frontmatter}

{/* ${GENERATED_MARKER} */}

${body}${learnBlock}${relatedTypes}
`;
}

// A page with several exports opens with the lead export's summary and a
// combined import block, then gives each export its own `##` section with
// the standard anatomy nested one level down.
function renderMultiEntryPage(entries) {
	const primary = entries[0];
	const blocks = [renderIntro(primary)];
	blocks.push(renderImport(entries));
	for (const entry of entries) {
		blocks.push(`## \`${entry.name}\``);
		blocks.push(
			renderEntry(entry, {
				heading: "###",
				skipIntro: entry === primary,
				skipImport: true,
			})
		);
	}
	return blocks.join("\n\n");
}

function renderIntro(entry) {
	const blocks = [
		escapeMdxText(entry.docs.summary) || `${entry.name} API reference.`,
	];
	if (ENTRY_CALLOUTS[entry.name]) blocks.push(ENTRY_CALLOUTS[entry.name]);
	if (entry.docs.deprecated) {
		blocks.push(`> Deprecated: ${escapeMdxText(entry.docs.deprecated)}`);
	}
	return blocks.join("\n\n");
}

function renderImport(entries, heading = "##") {
	const byPackage = new Map();
	for (const entry of entries) {
		const isType =
			!VALUE_IMPORTS.has(entry.name) &&
			(entry.kind === "type" || entry.kind === "namespace");
		const key = `${isType ? "import type" : "import"}|${entry.packageName}`;
		const current = byPackage.get(key) ?? [];
		current.push(entry.name);
		byPackage.set(key, current);
	}
	const lines = [...byPackage.entries()].map(([key, names]) => {
		const [keyword, packageName] = key.split("|");
		return `${keyword} { ${names.join(", ")} } from "${packageName}";`;
	});
	return `${heading} Import\n\n\`\`\`ts\n${lines.join("\n")}\n\`\`\``;
}

function renderEntry(
	entry,
	{ heading = "##", skipIntro = false, skipImport = false } = {}
) {
	const h = heading;
	const sub = `${heading}#`;
	const blocks = [];
	if (!skipIntro) blocks.push(renderIntro(entry));
	if (!skipImport) blocks.push(renderImport([entry], h));

	blocks.push(`${h} Type signature\n\n\`\`\`ts\n${entry.signature}\n\`\`\``);

	if (entry.isComponent && entry.props.length) {
		blocks.push(`${h} Props\n\n${renderMembers(entry.props, sub)}`);
	} else if (entry.parameters.length) {
		blocks.push(`${h} Parameters\n\n${renderMembers(entry.parameters, sub)}`);
	} else if (entry.docs.params.length) {
		blocks.push(
			`${h} Parameters\n\n${entry.docs.params
				.map(
					(param) =>
						`${sub} \`${param.name}\`\n\n${escapeMdxText(param.text) || "No description provided."}`
				)
				.join("\n\n")}`
		);
	}

	let returns = entry.docs.returns || RETURN_DOCS[entry.name];
	// Upstream `@returns` that is only a type gets the prose from RETURN_DOCS.
	if (
		returns &&
		RETURN_DOCS[entry.name] &&
		/^`[^`]+`$/.test(returns.trim()) &&
		returns !== RETURN_DOCS[entry.name]
	) {
		returns = `${returns.trim()}\n\n${RETURN_DOCS[entry.name]}`;
	}
	if (returns) {
		blocks.push(`${h} Return value\n\n${escapeMdxText(returns)}`);
	}

	if (entry.memberDocs.length) {
		blocks.push(
			`${h} Properties\n\n${renderMemberDocs(entry.memberDocs, sub)}`
		);
	}

	if (entry.docs.remarks && !OMIT_REMARKS.has(entry.name)) {
		blocks.push(`${h} Remarks\n\n${escapeMdxText(entry.docs.remarks)}`);
	}

	const examples = [
		...entry.docs.examples,
		...(ENTRY_EXAMPLES[entry.name] ?? []),
	];
	if (examples.length) {
		blocks.push(
			`${h} Examples\n\n${examples
				.map((example) => formatExample(example, sub))
				.join("\n\n")}`
		);
	}

	const caveats = ENTRY_CAVEATS[entry.name] ?? [];
	if (caveats.length) {
		blocks.push(
			`${h} Caveats\n\n${caveats.map((caveat) => `- ${caveat}`).join("\n")}`
		);
	}

	const problems = ENTRY_PROBLEMS[entry.name] ?? [];
	if (problems.length) {
		blocks.push(
			`${h} Common problems\n\n${problems
				.map(([label, href]) => `- [${label}](${href})`)
				.join("\n")}`
		);
	}

	const related = renderRelatedLinks(entry);
	if (related.length) {
		blocks.push(`${h} Related\n\n${related.join("\n")}`);
	}

	return blocks.join("\n\n");
}

function renderLearnLinks(entries, category) {
	const links = [];
	for (const entry of entries) links.push(...(ENTRY_LEARN[entry.name] ?? []));
	links.push(...(CATEGORY_LEARN[category] ?? []));
	const seen = new Set();
	return links
		.filter(([, href]) => (seen.has(href) ? false : seen.add(href)))
		.map(([label, href]) => `- [${label}](${href})`);
}

function renderRelatedTypes(entries) {
	return `## Related types

${entries.map(renderRelatedType).join("\n\n")}`;
}

function renderRelatedType(entry) {
	const summary = escapeMdxText(entry.docs.summary);
	if (COLLAPSED_RELATED_TYPES.has(entry.name)) {
		const inner = [];
		if (summary) inner.push(summary);
		inner.push(`\`\`\`ts\n${entry.signature}\n\`\`\``);
		if (entry.docs.remarks) inner.push(escapeMdxText(entry.docs.remarks));
		if (entry.memberDocs.length) {
			inner.push(renderMemberDocsInline(entry.memberDocs));
		}
		return `### \`${entry.name}\`\n\n:::deep-dive[${entry.name} members]\n${inner.join("\n\n")}\n:::`;
	}
	const blocks = [`### \`${entry.name}\``];
	if (summary) blocks.push(summary);
	blocks.push(`\`\`\`ts
${entry.signature}
\`\`\``);
	if (entry.docs.remarks) {
		blocks.push(escapeMdxText(entry.docs.remarks));
	}
	if (entry.memberDocs.length) {
		blocks.push(renderMemberDocs(entry.memberDocs, "####"));
	}
	return blocks.join("\n\n");
}

function renderMemberDocs(members, heading = "###") {
	return members
		.map((member) => {
			const parts = [`${heading} \`${member.name}\``];
			if (member.type) parts.push(`- **Type:** ${inlineCode(member.type)}`);
			if (member.text) parts.push(escapeMdxText(member.text));
			return parts.join("\n\n");
		})
		.join("\n\n");
}

// Member docs without headings, for use inside a collapsed deep-dive where
// headings would leak into the table of contents.
function renderMemberDocsInline(members) {
	return members
		.map((member) => {
			const head = member.type
				? `**\`${member.name}\`** — ${inlineCode(member.type)}`
				: `**\`${member.name}\`**`;
			return member.text ? `${head}\n\n${escapeMdxText(member.text)}` : head;
		})
		.join("\n\n");
}

// Parameters and props: one `###` per member with type, optionality, and text.
function renderMembers(members, heading) {
	return members
		.map((member) => {
			const parts = [`${heading} \`${member.name}\``];
			const meta = [];
			if (member.type) meta.push(`- **Type:** ${inlineCode(member.type)}`);
			if (member.optional) meta.push("- Optional");
			if (meta.length) parts.push(meta.join("\n"));
			if (member.text) parts.push(escapeMdxText(member.text));
			return parts.join("\n\n");
		})
		.join("\n\n");
}

// Frontmatter descriptions are one plain-text line of at most a few
// sentences; the page body carries the full summary.
function toDescription(value) {
	const flat = String(value)
		.replace(/\s+/g, " ")
		.replace(/\*\*([^*]+)\*\*/g, "$1")
		.replace(/(^|\s)\*([^*]+)\*(?=[\s.,;:)]|$)/g, "$1$2")
		.replace(/\\</g, "<")
		.trim();
	// Mask inline code and abbreviations so their periods do not end a sentence.
	const masked = [];
	const maskedText = flat.replace(
		/`[^`]*`|\b(?:e\.g|i\.e|etc|vs)\./gi,
		(match) => `\uE000${masked.push(match) - 1}\uE001`
	);
	const sentences = maskedText.match(/[^.!?]+[.!?]+(?=\s|$)|[^.!?]+$/g) ?? [
		maskedText,
	];
	let result = "";
	for (const sentence of sentences) {
		if (result && (result + sentence).length > 180) break;
		result += sentence;
	}
	const unmask = (text) =>
		text.replace(/\uE000(\d+)\uE001/g, (_m, index) => masked[Number(index)]);
	return unmask(result.trim()) || unmask(maskedText);
}

function inlineCode(value) {
	const text = String(value);
	const fence = text.includes("`") ? "``" : "`";
	return `${fence}${text}${fence}`;
}

// Examples are either raw strings (from `@example` tags or ENTRY_EXAMPLES)
// or `{ title, code }` objects, which render with a heading.
function formatExample(example, heading = "###") {
	if (typeof example === "object" && example !== null) {
		const code = formatExample(example.code, heading);
		return example.title ? `${heading} ${example.title}\n\n${code}` : code;
	}
	if (example.includes("```")) return example;
	return `\`\`\`ts
${example}
\`\`\``;
}

function renderRelatedLinks(entry) {
	const list = [
		...entry.docs.see.map((value) => value.trim()),
		...entry.docs.related.map((value) => value.trim()),
		...entry.aliases.map((value) => value.trim()),
	].filter(Boolean);

	const links = uniqueStrings(list).map((item) => {
		if (item.startsWith("[") || item.startsWith("http")) {
			return `- ${item}`;
		}

		const symbol = item.replace(/^`|`$/g, "").trim();
		const route = getRouteForSymbol(symbol);
		if (!route) return `- \`${escapeLinkLabel(symbol)}\``;

		const href = toReferenceHref(route.outputPath);
		return `- [\`${escapeLinkLabel(symbol)}\`](${href})`;
	});

	return uniqueStrings(links);
}

function buildFrontmatterTags(entries, category) {
	const symbols = entries.map((entry) => entry.name);
	const symbolTokens = symbols
		.flatMap((symbol) => symbolToTagTokens(symbol))
		.filter(Boolean);
	const categoryTokens = humanizeCategory(category)
		.toLowerCase()
		.split(/[^a-z0-9]+/)
		.filter(Boolean);
	const customTags = entries.flatMap((entry) => entry.docs.tags || []);

	return uniqueStrings([
		...customTags.map((tag) => tag.toLowerCase()),
		...symbolTokens,
		...categoryTokens,
		"reference",
		"api",
		"v2",
	]);
}

function symbolToTagTokens(symbol) {
	return String(symbol)
		.replace(/([a-z0-9])([A-Z])/g, "$1 $2")
		.toLowerCase()
		.split(/[^a-z0-9]+/)
		.filter(Boolean);
}

function humanizeCategory(category) {
	return String(category)
		.replace(/\s*\/\s*/g, " ")
		.trim();
}

function escapeMdxText(value) {
	return splitFencedCode(value)
		.map((part) =>
			part.fence ? part.text : escapeAnglesOutsideInlineCode(part.text)
		)
		.join("");
}

function splitFencedCode(value) {
	const parts = [];
	const pattern = /```[\s\S]*?```/g;
	let lastIndex = 0;
	let match;
	while ((match = pattern.exec(value))) {
		if (match.index > lastIndex)
			parts.push({ fence: false, text: value.slice(lastIndex, match.index) });
		parts.push({ fence: true, text: match[0] });
		lastIndex = pattern.lastIndex;
	}
	if (lastIndex < value.length)
		parts.push({ fence: false, text: value.slice(lastIndex) });
	return parts;
}

function escapeAnglesOutsideInlineCode(value) {
	return value
		.split(/(`[^`]*`)/g)
		.map((part) =>
			part.startsWith("`")
				? part
				: part.replace(
						/<([A-Za-z][^>\n]*)>/g,
						(_match, inner) => `&lt;${inner}&gt;`
					)
		)
		.join("");
}

function writeFiles(files) {
	cleanGeneratedFiles(outDir);
	for (const file of files) {
		fs.mkdirSync(path.dirname(file.fullPath), { recursive: true });
		fs.writeFileSync(file.fullPath, file.content);
	}
}

function cleanGeneratedFiles(dir) {
	if (!fs.existsSync(dir)) return;
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const fullPath = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			cleanGeneratedFiles(fullPath);
			if (fs.readdirSync(fullPath).length === 0) fs.rmdirSync(fullPath);
			continue;
		}
		if (entry.isFile() && fullPath.endsWith(".mdx")) {
			// The output directory also holds hand-written pages (other
			// packages, section indexes); only remove generated files.
			const content = fs.readFileSync(fullPath, "utf8");
			if (content.includes(GENERATED_MARKER)) fs.unlinkSync(fullPath);
		}
	}
}

function stripRouteOrdering(routePath) {
	return routePath
		.split("/")
		.map((part) => part.replace(/^\(\d+\)/, ""))
		.join("/");
}

function toReferenceHref(routePath) {
	const normalized = stripRouteOrdering(routePath).replace(/\.mdx$/, "");
	return `/reference/${normalized}`;
}

function escapeLinkLabel(value) {
	return String(value)
		.replace(/\\/g, "\\\\")
		.replace(/\[/g, "\\[")
		.replace(/\]/g, "\\]");
}

